// Rich fallback generator for teaching materials
export function generateFallbackTeachingMaterials(
  type: string,
  subject: string,
  grade: string,
  chapter: string,
  lessonTitle: string,
  subTopic: string,
  targetAudience: string,
  itemCount: number,
  schoolName: string
): string {
  const isPhysics = subject.includes('រូបវិទ្យា') || subTopic.includes('សីតុណ្ហភាព') || subTopic.includes('កម្តៅ');
  const isChemistry = subject.includes('គីមី');
  const isBiology = subject.includes('ជីវ');
  const isMath = subject.includes('គណិត');
  const isKhmer = subject.includes('ខ្មែរ');

  if (type === 'flashcards') {
    return generateFlashcardsContent(subject, grade, lessonTitle, subTopic, itemCount, isPhysics, isMath, isChemistry, isBiology, isKhmer);
  }

  if (type === 'concept_poster') {
    return generateConceptPosterContent(subject, grade, chapter, lessonTitle, subTopic, schoolName, isPhysics, isMath, isChemistry);
  }

  if (type === 'group_task_cards') {
    return generateGroupTaskCardsContent(subject, grade, lessonTitle, subTopic, isPhysics, isMath);
  }

  if (type === 'lab_guide') {
    return generateLabGuideContent(subject, grade, lessonTitle, subTopic, isPhysics, isChemistry, isBiology);
  }

  if (type === 'rubric_sheet') {
    return generateRubricContent(subject, grade, lessonTitle, subTopic);
  }

  // Default: student cheat sheet
  return generateCheatSheetContent(subject, grade, chapter, lessonTitle, subTopic, isPhysics, isMath);
}

