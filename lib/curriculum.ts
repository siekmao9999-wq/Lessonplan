export function getSubjectsForGrade(grade: string): string[] {
  if (SUBJECTS_BY_GRADE[grade]) {
    return SUBJECTS_BY_GRADE[grade];
  }
  if (PRIMARY_GRADES.includes(grade)) {
    return SUBJECTS_BY_GRADE['ថ្នាក់ទី៤'];
  }
  if (LOWER_SECONDARY_GRADES.includes(grade)) {
    return SUBJECTS_BY_GRADE['ថ្នាក់ទី៨'];
  }
  return SUBJECTS_BY_GRADE['ថ្នាក់ទី១១'];
}

